package app.remix.player
fun main(){
    val lines=listOf(LyricLineSearch.Line("Всё, что было",1000),LyricLineSearch.Line("Café déjà vu",2500),LyricLineSearch.Line("Всё, что было",4000),LyricLineSearch.Line("Unmarked"))
    check(LyricLineSearch.find(lines,"все что").map{it.ms}==listOf(1000L,4000L))
    check(LyricLineSearch.find(lines,"CAFE DEJA").single().ms==2500L)
    check(LyricLineSearch.find(lines,"unmarked").single().ms==null)
    check(LyricLineSearch.find(lines,"???").isEmpty())
    check(LyricLineSearch.find(lines,"missing").isEmpty())
    check(LyricLineSearch.find(List(1000){LyricLineSearch.Line("match",it.toLong())},"match").size==80)
    check(LyricLineSearch.pair(lines,"One\nTwo\nThree\nFour")?.get(1)?.original?.ms==2500L)
    check(LyricLineSearch.pair(lines,"One\nTwo")==null)
    check(LyricLineSearch.pair(lines,"One\n\nTwo\nThree\nFour")?.size==4)
    check(LyricLineSearch.pair(lines,"x".repeat(64001))==null)
    val russian=listOf(LyricLineSearch.Line("мой",1000),LyricLineSearch.Line("мои",2000))
    check(LyricLineSearch.find(russian,"мой").single().ms==1000L)
    check(LyricLineSearch.find(russian,"мои").single().ms==2000L)
    check(LyricLineSearch.normalize("и\u0306")=="й")
    check(LyricLineSearch.normalize("е\u0308")=="е")
    val large=(0 until 10000).map{LyricLineSearch.Line(if(it%10==0)"Всё, мой Café $it" else "иная строка $it",it.toLong())}.toMutableList()
    val index=LyricLineSearch.Index(large)
    check(index.find("все мой cafe").size==80)
    check(index.find("все мои cafe").isEmpty())
    check(index.find("иная строка 9999").single().ms==9999L)
    check(index.find("!!!").isEmpty())
    check(index.find("Всё, мой Café 20")==LyricLineSearch.find(large,"Всё, мой Café 20"))
    large.clear();check(index.find("иная строка 9999").single().ms==9999L)
    check(LyricLineSearch.Index(emptyList()).find("any").isEmpty())
    println("PASS: 21 lyric search, translation and indexed search checks")
}
