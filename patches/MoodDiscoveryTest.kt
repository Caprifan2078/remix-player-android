package app.remix.player
fun main(){
 val sad=MoodDiscovery.Features(.23,.20,.30,.35,.20,.40)
 val gym=MoodDiscovery.Features(.87,.88,.50,.72,.8,.30)
 val uncertain=sad.copy(valence=null)
 val p=MoodDiscovery.profiles.associateBy{it.title}
 check(p.size==8)
 check(MoodDiscovery.score(sad,p.getValue("Меланхолия"))!!>.95)
 check(MoodDiscovery.score(gym,p.getValue("Меланхолия"))==null)
 check(MoodDiscovery.score(uncertain,p.getValue("Меланхолия"))==null)
 check(MoodDiscovery.score(gym,p.getValue("Тренировка"))!!>.95)
 check(MoodDiscovery.score(sad,p.getValue("Тренировка"))==null)
 val rows=listOf(MoodDiscovery.Entry("1","A",sad),MoodDiscovery.Entry("2","A",sad),MoodDiscovery.Entry("3","B",sad),MoodDiscovery.Entry("1","A",sad))
 check(MoodDiscovery.rank(rows,p.getValue("Меланхолия"))==listOf("1","3","2"))
 check(MoodDiscovery.rank(rows,p.getValue("Меланхолия"),2)==listOf("1","3"))
 val unknown=listOf(MoodDiscovery.Entry("1","",sad),MoodDiscovery.Entry("2","A",sad.copy(energy=.30)))
 check(MoodDiscovery.rank(unknown,p.getValue("Меланхолия")).first()=="1")
 val r=MusicAnalysis.Report(null,null,null,0.0,0.0,20.0,listOf(0.0,0.0))
 check(MoodDiscovery.from(r)==null)
 val spec=SoundProfile.Features(.35,.5,.15,500.0,30)
 val frame=SectionMap.Frame(0.0,.04,.35,.5,.15,.20,List(12){1.0/12})
 val measured=r.copy(key="A minor",keyConfidence=.15,rms=.04,energy=listOf(.02,.04,.06,.08,.09),spectrum=spec,featureFrames=listOf(frame))
 val actual=MoodDiscovery.from(measured)!!
 check(actual.valence==.2&&actual.activity==.2)
 check(MoodDiscovery.from(measured.copy(keyConfidence=0.0))!!.valence==null)
 val many=(0 until 10000).map{MoodDiscovery.Entry(it.toString(),"Artist "+it%50,sad)}
 check(MoodDiscovery.rank(many,p.getValue("Меланхолия"),100).distinct().size==100)
 val zero=MoodDiscovery.Profile("Test","",0.0,0.0,0.0,0.0,null,0.0)
 val edge=MoodDiscovery.Features(.94,0.0,0.0,0.0,null,0.0)
 check(MoodDiscovery.score(edge,zero)==null)
 check(kotlin.math.abs(MoodDiscovery.score(edge.copy(energy=.5),zero)!!-(1-.16/.92))<1e-9)
 val perfect=edge.copy(energy=0.0)
 check(MoodDiscovery.score(perfect,zero)==1.0)
 check(MoodDiscovery.score(perfect,zero.copy(valence=.2))==null)
 check(MoodDiscovery.score(perfect.copy(valence=.8),zero.copy(valence=.2))==null)
 val clean=listOf(MoodDiscovery.Entry("","A",perfect),MoodDiscovery.Entry("1","A",perfect),MoodDiscovery.Entry("2"," a ",perfect),MoodDiscovery.Entry("3","B",perfect),MoodDiscovery.Entry("1","A",perfect))
 check(MoodDiscovery.rank(clean,zero)==listOf("1","3","2"))
 val profiles=MoodDiscovery.profiles
 check(MoodDiscovery.describe("Грустная музыка с глубоким басом")?.let{it.valence==.18&&it.low==.85}==true)
 check(MoodDiscovery.describe("спокойная музыка")==profiles[1])
 check(MoodDiscovery.describe("GYM bass")?.low==.85)
 check(MoodDiscovery.describe("без баса")==null)
 check(MoodDiscovery.describe("грустная и весёлая")==null)
 check(MoodDiscovery.describe("неизвестно")==null)
 check(MoodDiscovery.describe("а".repeat(161))==null)
 check(MoodDiscovery.describe("бас")?.low==.85)
 fun point(id:String,x:Double)=MoodDiscovery.Entry(id,id,MoodDiscovery.Features(x,x,.4,.4,null,.4))
 val start=MoodDiscovery.Profile("a","",.1,.1,.4,.4,null,.4)
 val end=start.copy(energy=.9,activity=.9)
 val journeyRows=listOf(point("low",.1),point("mid",.5),point("high",.9),point("low",.1),point("",.1))
 check(MoodDiscovery.journey(journeyRows,start,end,3)==listOf("low","mid","high"))
 check(MoodDiscovery.journey(journeyRows,end,start,3)==listOf("high","mid","low"))
 check(MoodDiscovery.journey(journeyRows,start,end,1)==listOf("mid"))
 check(MoodDiscovery.journey(emptyList(),start,end).isEmpty())
 check(MoodDiscovery.journey(journeyRows,start,end,30).distinct().size==3)
 check(runCatching{MoodDiscovery.journey(journeyRows,start,end,0)}.isFailure)
 println("PASS: 33 mood, description and journey checks")
}
